#!/usr/bin/env node
// Packages the PREL40 lab files for the Skillable VM and publishes a one-command updater as a secret gist.
//
// Usage: node scripts/publish-vm-update.mjs [--no-upload]
//
// Writes scripts/dist/lab-files.zip and scripts/dist/prel40-vm-update.ps1 (the zip embedded as base64),
// uploads the .ps1 as a secret gist, deletes the gists from earlier runs, and prints the PowerShell
// command to run on the VM. Progress goes to stderr; the VM command is the only stdout output.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import zlib from 'node:zlib';

const GIST_DESCRIPTION = 'PREL40 lab VM update (generated by scripts/publish-vm-update.mjs)';
const PS1_NAME = 'prel40-vm-update.ps1';
const ZIP_NAME = 'lab-files.zip';

// Repo paths (relative to the repo root) and where they go inside the zip.
// The VM script (vm-update.template.ps1) relies on these zip paths.
const GROUPS = [
  { name: 'template', source: 'src/home-loan-desk', target: 'template/home-loan-desk', required: ['rayfin-template.yml', 'package.json'] },
  { name: 'data', source: 'data/portfolio-seed.sql', target: 'data/portfolio-seed.sql' },
  { name: 'data', source: 'data/samples', target: 'data/samples', required: ['HL-1042-floor-plan.pdf', 'HL-1042-kitchen-current.jpg'] },
  { name: 'skill', source: 'scripts/vm-skills/check-setup', target: 'skills/check-setup', required: ['SKILL.md', 'check-setup.ps1'] },
  { name: 'skill', source: 'scripts/vm-skills/lab-checkpoint', target: 'skills/lab-checkpoint', required: ['SKILL.md'] },
  { name: 'checkpoints', source: 'scripts/checkpoints', target: 'checkpoints', required: ['checkpoint.mjs', 'package.json', 'package-lock.json'] },
  { name: 'checkpoints', source: 'data/generator/manifest.json', target: 'checkpoints/manifest.json' },
];

const scriptDir = dirname(fileURLToPath(import.meta.url));
const distDir = join(scriptDir, 'dist');

class UserError extends Error {}

const log = (message = '') => process.stderr.write(`${message}\n`);

function run(command, args, options = {}) {
  try {
    return execFileSync(command, args, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 64 * 1024 * 1024,
      ...options,
    }).trim();
  } catch (error) {
    if (error.code === 'ENOENT') throw new UserError(`${command} is not installed or not on PATH.`);
    const details = (error.stderr || error.stdout || error.message).toString().trim();
    throw new UserError(`${command} ${args.join(' ')} failed:\n${details}`);
  }
}

function collectFiles(repoRoot) {
  const files = [];
  for (const group of GROUPS) {
    const listed = run('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', group.source], { cwd: repoRoot })
      .split('\0')
      .filter(Boolean);
    const present = listed.filter((path) => existsSync(join(repoRoot, path)) && statSync(join(repoRoot, path)).isFile());
    if (present.length === 0) throw new UserError(`Nothing to package in ${group.source}`);
    for (const required of group.required ?? []) {
      const path = `${group.source}/${required}`;
      if (!present.includes(path)) throw new UserError(`Missing required file: ${path}`);
    }
    for (const path of present) {
      files.push({
        group: group.name,
        source: path,
        name: group.target + path.slice(group.source.length),
      });
    }
  }
  return files;
}

function toDosDateTime(date) {
  const time = (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2);
  const day = ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
  return { time, day };
}

// Minimal zip writer (deflate, UTF-8 names, no zip64). Enough for a few hundred small files.
function createZip(entries, date) {
  if (entries.length > 0xffff) throw new UserError('Too many files for the zip writer.');
  const { time, day } = toDosDateTime(date);
  const parts = [];
  const central = [];
  let offset = 0;

  for (const { name, data } of entries) {
    const nameBuffer = Buffer.from(name, 'utf8');
    const deflated = zlib.deflateRawSync(data, { level: 9 });
    const stored = deflated.length >= data.length;
    const body = stored ? data : deflated;
    const crc = zlib.crc32(data);

    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50, 0);
    header.writeUInt16LE(20, 4);
    header.writeUInt16LE(0x0800, 6);
    header.writeUInt16LE(stored ? 0 : 8, 8);
    header.writeUInt16LE(time, 10);
    header.writeUInt16LE(day, 12);
    header.writeUInt32LE(crc, 14);
    header.writeUInt32LE(body.length, 18);
    header.writeUInt32LE(data.length, 22);
    header.writeUInt16LE(nameBuffer.length, 26);

    const record = Buffer.alloc(46);
    record.writeUInt32LE(0x02014b50, 0);
    record.writeUInt16LE(20, 4);
    record.writeUInt16LE(20, 6);
    record.writeUInt16LE(0x0800, 8);
    record.writeUInt16LE(stored ? 0 : 8, 10);
    record.writeUInt16LE(time, 12);
    record.writeUInt16LE(day, 14);
    record.writeUInt32LE(crc, 16);
    record.writeUInt32LE(body.length, 20);
    record.writeUInt32LE(data.length, 24);
    record.writeUInt16LE(nameBuffer.length, 28);
    record.writeUInt32LE(offset, 42);

    parts.push(header, nameBuffer, body);
    central.push(record, nameBuffer);
    offset += header.length + nameBuffer.length + body.length;
  }

  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, directory, end]);
}

function fill(template, values) {
  let output = template;
  for (const [key, value] of Object.entries(values)) {
    if (!output.includes(key)) throw new UserError(`Placeholder ${key} not found in vm-update.template.ps1.`);
    output = output.split(key).join(value);
  }
  return output;
}

const sha256 = (data) => createHash('sha256').update(data).digest('hex').toUpperCase();
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function listPreviousGists() {
  const lines = run('gh', ['api', 'gists', '--paginate', '--jq', '.[] | {id, description} | @json']);
  return lines
    .split('\n')
    .filter(Boolean)
    .map((line) => JSON.parse(line))
    .filter((gist) => gist.description === GIST_DESCRIPTION)
    .map((gist) => gist.id);
}

async function findVerifiedRawUrl(candidates, expectedHash) {
  for (let attempt = 1; attempt <= 5; attempt++) {
    for (const url of candidates) {
      try {
        const response = await fetch(url, { cache: 'no-store' });
        if (response.ok && sha256(Buffer.from(await response.arrayBuffer())) === expectedHash) return url;
      } catch {
        // Retried below: a new gist can take a few seconds to be served.
      }
    }
    await sleep(attempt * 2000);
  }
  return null;
}

async function upload(ps1Path, ps1Hash) {
  log('Uploading the update script as a secret gist...');
  const previous = listPreviousGists();
  const gistUrl = run('gh', ['gist', 'create', '--desc', GIST_DESCRIPTION, ps1Path]).split('\n').pop();
  const id = gistUrl.split('/').pop();
  const gist = JSON.parse(run('gh', ['api', `gists/${id}`, '--jq', `{owner: .owner.login, public: .public, raw: .files["${PS1_NAME}"].raw_url}`]));
  if (gist.public) throw new UserError(`Gist ${gistUrl} is public. Delete it with: gh gist delete ${id} --yes`);

  const base = `https://gist.githubusercontent.com/${gist.owner}/${id}/raw`;
  const rawUrl = await findVerifiedRawUrl([base, `${base}/${PS1_NAME}`, gist.raw], ps1Hash);
  if (!rawUrl) throw new UserError(`Couldn't verify the uploaded script at ${base}. Check the gist: ${gistUrl}`);
  log(`Gist: ${gistUrl} (secret, content verified)`);

  for (const oldId of previous.filter((oldId) => oldId !== id)) {
    try {
      run('gh', ['gist', 'delete', oldId, '--yes']);
      log(`Deleted previous gist ${oldId}`);
    } catch (error) {
      log(`Warning: couldn't delete previous gist ${oldId}: ${error.message}`);
    }
  }
  return rawUrl;
}

async function main() {
  const { values } = parseArgs({ options: { 'no-upload': { type: 'boolean', default: false }, help: { type: 'boolean', short: 'h' } } });
  if (values.help) {
    log('Usage: node scripts/publish-vm-update.mjs [--no-upload]');
    log('  --no-upload  Build scripts/dist/ only; skip the gist upload.');
    return;
  }
  if (typeof zlib.crc32 !== 'function') throw new UserError('Node.js 22 or later is required.');

  const repoRoot = run('git', ['rev-parse', '--show-toplevel'], { cwd: scriptDir });
  const commit = run('git', ['rev-parse', 'HEAD'], { cwd: repoRoot });
  const sources = GROUPS.map((group) => group.source);
  const changes = run('git', ['status', '--porcelain', '--', ...sources], { cwd: repoRoot });
  const dirty = changes.length > 0;
  if (dirty) log(`Warning: packaging uncommitted changes in ${changes.split('\n').length} file(s).`);

  const files = collectFiles(repoRoot);
  const builtAt = new Date();
  const counts = Object.fromEntries(GROUPS.map((group) => [group.name, files.filter((file) => file.group === group.name).length]));
  const manifest = {
    name: 'PREL40 lab files',
    commit,
    shortCommit: commit.slice(0, 7),
    dirty,
    builtAt: `${builtAt.toISOString().slice(0, 16).replace('T', ' ')} UTC`,
    files: counts,
  };

  const entries = [
    { name: 'manifest.json', data: Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`) },
    ...files.map((file) => ({ name: file.name, data: readFileSync(join(repoRoot, file.source)) })),
  ];
  const zip = createZip(entries, builtAt);
  const build = { ...manifest, sha256: sha256(zip) };

  const template = readFileSync(join(scriptDir, 'vm-update.template.ps1'), 'utf8');
  const ps1 = fill(template, {
    __BUILD_JSON__: JSON.stringify(build),
    __PAYLOAD_BASE64__: zip.toString('base64').match(/.{1,120}/g).join('\n'),
  });

  rmSync(distDir, { recursive: true, force: true });
  mkdirSync(distDir, { recursive: true });
  const ps1Path = join(distDir, PS1_NAME);
  writeFileSync(join(distDir, ZIP_NAME), zip);
  writeFileSync(ps1Path, ps1);

  const summary = Object.entries(counts).map(([name, count]) => `${name} ${count}`).join(', ');
  log(`Built ${ZIP_NAME} (${(zip.length / 1024).toFixed(0)} KB; ${summary} files) at ${manifest.shortCommit}${dirty ? ' with local changes' : ''}`);
  log(`Wrote ${ps1Path} (${(Buffer.byteLength(ps1) / 1024).toFixed(0)} KB)`);

  if (values['no-upload']) {
    log('Skipped upload (--no-upload).');
    return;
  }

  const rawUrl = await upload(ps1Path, sha256(Buffer.from(ps1)));
  log('');
  log('Run this command in PowerShell on the lab VM:');
  log('');
  process.stdout.write(`[Net.ServicePointManager]::SecurityProtocol='Tls12'; irm ${rawUrl} | iex\n`);
}

main().catch((error) => {
  log(error instanceof UserError ? `Error: ${error.message}` : error.stack);
  process.exitCode = 1;
});
